import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"d178": ("抱き合ったまま、二人は静かに眠りに落ちた。エコー写真が、月明かりにそっと白く浮かんでいた。",
         "優奈さんのお腹にそっと手を当てたまま、俺は深い眠りに沈んでいった。エコー写真が、月明かりにそっと白く浮かんでいた。"),
"d216": ("抱き合ったまま、二人は静かに眠りに落ちた。名前の本が、月明かりにそっと白く浮かんでいた。",
         "決めた名前をそっと口の中で転がしながら、二人は寄り添って目を閉じた。名前の本が、月明かりにそっと白く浮かんでいた。"),
"d254": ("抱き合ったまま、二人は静かに眠りに落ちた。栞の花束が、月明かりにそっと白く浮かんでいた。",
         "明日会える命の鼓動に耳を澄ませながら、二人は寄り添って眠りについた。栞の花束が、月明かりにそっと白く浮かんでいた。"),
"d197": ("ねえ悠太さん、今日から、わたしの特等席はあなたのそば。……図書館でも、家でもね。",
         "ねえ悠太さん、今日から、わたしの隣はいつもあなたの場所よ。……図書館でも、家でもね。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
