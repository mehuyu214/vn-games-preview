# -*- coding: utf-8 -*-
"""W2 美咲 D4: 関係段階に対する親密さの積み上げの逆転の解消（美咲編）。
レビュー D4「告白前の b231 では美咲が悠太の肩に頭を預け、b232 では
『食堂ができたら朝ごはんは二人で作るの』と将来の共同作業まで語る。その直後
のプレイ順にある b42 では、連絡先を交換しただけで『心臓の音が、自分でも
分かるくらい大きい』。挿入ブロックの配置（C1／C3）によって距離感の階段が
崩れ、序盤の緊張感が後付けで痩せて見える」への対応。

実測（着手前、GOOD ルートのプレイ順、0 起点）:
- b231（pos 18）「美咲さんは缶コーヒーを置き、俺の肩にそっと頭を預けた。
  雨音が、店の外で静かに響いている。」→ b232（pos 19）「ねえ、悠太くん。
  食堂ができたらさ、朝ごはんは二人で作るの。悠太くんは卵焼き担当ね。
  わたしの、弟子一号。」—— 肩に頭を預ける親密さ＋将来の共同作業の約束。
- b39（pos 26）「彼女いるの？」→ b40（pos 27）→ b41（pos 28）「ねえ、
  連絡先、交換しよ。バイトの連絡だけじゃなくて、普通に話したいな、わたし。」
  → b42（pos 29）「心臓の音が、自分でも分かるくらい大きい。」——
  肩に頭を預け、将来の話までした 10 ノード後に、初対面級の緊張感が来る
  逆転を確認。
- b231／b232 の親密さ自体は休憩ブロックの魅力のため残置し、b42 側を
  書き換える。b41「バイトの連絡だけじゃなくて、普通に話したいな」との
  接続も維持する。

改稿（text のみ 1 ノード、他作品・構造は無変更）:
- b42: 鼓動の理由を「初めての接触の緊張」から「休憩の親密さが連絡先の
  交換で店の外へ続いていく現実味」に書き換え、肩に頭を預けた出来事への
  言及を入れる。鼓動の一文自体は残す。
"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"b42": ("スマホを交換し、連絡先を登録する。美咲さんのアイコンは、私服姿の笑顔だった。心臓の音が、自分でも分かるくらい大きい。",
        "スマホを交換し、連絡先を登録する。美咲さんのアイコンは、私服姿の笑顔だった。休憩のとき、肩に頭を預けてくれたあの温かさが、今度は画面の向こうから続いていくと思うと――心臓の音が、自分でも分かるくらい大きい。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
