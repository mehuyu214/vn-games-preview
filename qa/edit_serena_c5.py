import io, sys

PATH = "data.js"

REPLACEMENTS = {
"e238": ("――結婚式前夜。セレナはウェディングドレスを広げ、俺の部屋で嬉しそうに笑った。白いバラの香りが、静かに漂っている。",
          "――結婚式前夜。セレナはウェディングドレスを広げ、俺の部屋で嬉しそうに笑った。白いバラの香りが、静かに漂っている。ドレス越しにお腹へそっと手を当てると、小さな命の胎動を感じた。"),
"e200": ("――結婚式のリハーサルを終えた夜。セレナは教会のパンフレットを広げ、俺の部屋で嬉しそうに笑った。バラの香りが、静かに漂っている。",
          "――結婚式のリハーサルを終えた夜。セレナは教会のパンフレットを広げ、俺の部屋で嬉しそうに笑った。リハーサルを終えた安堵と、明日への高揚が、彼女の笑顔に滲んでいた。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        # text フィールドの引用符付き完全一致で置換（他ノードへの誤爆防止）
        needle = '"' + old + '"'
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, '"' + new + '"', 1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
