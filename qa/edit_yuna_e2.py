"""W2 優奈 E2: 展開が初夜の時点で最後まで確定している。d35x の妊娠希望表明
→d63 の遅れの告白→d65「最後の確認」→d124 の陽性判明と、すべて予告通りに
進行し、逆転・誤解・すれ違いは全編を通じて一度もない。
再計測：優奈編全体で「誤解/すれ違い/喧嘩/言い合い/衝突/勘違い」0件、
「まさか/予想外/意外」0件、「頓挫/中止/延期」0件。「遅れ」は d63 の1件のみ。
レビュー提案（review_yuna.md L116）：読み聞かせの会の準備が一度頓挫する、
図書館の同僚に二人の関係が知られる、といった小さな事件を1つ差し込む。
同僚の方は d182-d184 で既に実装済み（「バレてるのかしら」→ d184 で
「隠し通すのって、二人の恋を否定するみたいで、嫌なの」と即解消）。
d88 の「もし陽性じゃなかったら」も既に疑いの表明があるが、その場で
d89 に解消されるため、事件としての揺さぶりにはなっていない。
残るのは読み聞かせの会の頓挫のみ。d62（「――数週間後」の橋渡し地の文）に、
読み聞かせの会の準備が一度頓挫しかけたことと、優奈さんが企画書を書き直して
立て直したことを1文で追加する。頓挫と立て直しを同一ノード内で完結させ、
新たな未回収の糸は残さない。d151 の「無謀かしら」という夢の宣言と
d154 の「一番最初のお客さん」の約束に接続し、夢の追求に一度だけ
失敗と回復の起伏を入れる。全員成人・合意ありは維持。text のみ変更。
ノードID・構造は不変。"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"d62": ("――数週間後。閉館後の書庫は、二人だけの逢瀬の場所になった。ある夜、優奈さんが真剣な顔で切り出す。",
        "――数週間後。閉館後の書庫は、二人だけの逢瀬の場所になった。その間、読み聞かせの会の準備は一度頓挫しかけた。日程が合わず、優奈さんが落ち込んだ夜もあったけれど、彼女は企画書を書き直して、もう一度だけ頑張ると笑った。ある夜、優奈さんが真剣な顔で切り出す。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        needle = '"' + old + '"'
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, '"' + new + '"', 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
