# -*- coding: utf-8 -*-
"""W2 美咲 D1: 夢の「初告白」の三重提示の解消（美咲編）。
レビュー D1「b150 で『わたしの夢、笑わない？』と打ち明け、b186 では
『ねえ悠太くん。わたしの夢、知ってる？』と改めて問う。ところがプレイ順では、
それより前に b219–b237 で献立・店名・看板の字まで二人で語り合っており、
b186 の問いは『知らない前提』で書かれた明らかな重複演出になっている」への対応。

実測（着手前、GOOD ルートのプレイ順、0 起点）:
- b219–b237（pos 6–24）休憩ブロック：食堂の夢を既に詳しく語り合っている。
  b223（pos 10）「帰ったら、食堂のメニューを考えるの」、
  b229（pos 16）「食堂の名前、まだ決まらないの」、
  b230 看板の字、b232「食堂ができたらさ、朝ごはんは二人で作るの」、
  b235「夢の話をする彼女の横顔は、少しだけ誇らしげだった」、
  b237（pos 24）「食堂の話、また聞かせてくださいね」。
- b150（pos 37）「でしょ？　……わたしね、いつか自分の小さな食堂を
  やりたいの。……夜勤の人たちが、ほっとできる場所を。」、
  b152（pos 39）「ねえ悠太くん。……わたしの夢、笑わない？　……
  コンビニで働きながら、いつか自分の店を持つなんて、無謀だよね。」
  —— 休憩ブロックの後なのに初告白の体裁で、残存そのもの。
- b186（pos 106）は現行文が「ねえ、悠太くん。……あの朝、わたしの夢、
  笑わないで聞いてくれたよね。あれが嬉しくて、ずっと考えてたの。」と
  既に b150／b152 への言及（コールバック）になっており、レビュー引用の
  「わたしの夢、知ってる？」は現行文に存在しないため残置。
- b84（pos 53）の回想「わたしの夢ね、いつか自分の小さな食堂を開くこと」
  は「――回想：ある夜勤明け」の中で、回想の夜における初出として整合する
  ため残置。b199（pos 119）「わたしの夢、叶えようね。二人で。」は
  前向きな決意表明のため残置。

改稿（text のみ 2 ノード、他作品・構造は無変更）:
- b150: 初告白の体裁をやめ、休憩で話した食堂の話の続きとして語らせる。
  「夜勤の人たちが、ほっとできる場所にしたい」という動機の中核は維持。
- b152: 「笑わない？」は残し（b153「笑いませんよ」との応答関係を維持）、
  「もう知ってるよね、休憩のときに話した食堂のこと」と既知であることを
  明示して、初めて打ち明ける体裁を解消する。不安の提示（「無謀だよね」）
  はそのまま残す。
"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"b150": ("でしょ？　……わたしね、いつか自分の小さな食堂をやりたいの。……夜勤の人たちが、ほっとできる場所を。",
        "でしょ？　……休憩のときに話した食堂のこと、覚えてる？　……夜勤の人たちが、ほっとできる場所にしたいの。……この朝ごはんみたいな、温かい場所を。"),
"b152": ("ねえ悠太くん。……わたしの夢、笑わない？　……コンビニで働きながら、いつか自分の店を持つなんて、無謀だよね。",
        "ねえ悠太くん。……わたしの夢、笑わない？　……もう知ってるよね、休憩のときに話した食堂のこと。コンビニで働きながら、いつか自分の店を持つなんて、無謀だよね。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
