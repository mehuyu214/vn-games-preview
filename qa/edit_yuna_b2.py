# -*- coding: utf-8 -*-
"""W2 優奈 B2（残り）: 4ブロックのクライマックス台詞の書き分け（優奈編）。
レビュー B2「テンプレートの残留文が場面と食い違う」への対応の残り。

現状（実測）:
- d138（α・陽性判明の夜）: 「中に出して……ねえ、悠太さん……もう
  宿っている命に、あなたの愛を重ねて……わたしのお腹、いっぱいの愛
  で満たして……！」――αの文として残置。
- d175（β・妊婦健診の帰りの夜）: 「中に出して……ねえ、悠太さん……
  もう宿っている命に、あなたの愛を重ねて……この子と、わたしを、い
  っぱいの愛で満たして……！」――中核句「もう宿っている命に、あなた
  の愛を重ねて」が d138 と完全一致（全作品でこの句はこの2件のみ）。
- d213（γ・命名の夜）: 「栞への、命名の夜の贈りもの……」とブロック
  固有の文言に書き分け済み。残置。
- d251（δ・産休初日の夜）: 「出産前、最後の夜かもしれないの……
  栞への、最初の贈りものに……」とブロック固有の文言に書き分け済み。
  残置。

改稿（text のみ 1 ノード、他作品・構造は無変更）:
- d175: βブロックのモチーフであるエコー写真（d161「エコー写真を
  広げ」、d173「この子のいちばん近くまで」）に寄せ、中核句を「エコ
  ー写真の小さな影に届くように、あなたの愛を重ねて」に書き換え。
  末尾「この子と、わたしを、いっぱいの愛で満たして……！」は維持し、
  d176「その手は、ずっとお腹を守るように添えられていた」との接続も
  維持。
"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"d175": ("中に出して……ねえ、悠太さん……もう宿っている命に、あなたの愛を重ねて……この子と、わたしを、いっぱいの愛で満たして……！",
         "中に出して……ねえ、悠太さん……エコー写真の小さな影に届くように、あなたの愛を重ねて……この子と、わたしを、いっぱいの愛で満たして……！"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
