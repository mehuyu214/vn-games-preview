import io, sys

PATH = "data.js"

REPLACEMENTS = {
"d127": ("優奈さんは電話越しに、そっと笑った。受話器の向こうで、彼女の涙が、静かに零れている。",
        "優奈さんは電話越しに、そっと笑った。受話器の向こうで、彼女の涙が、静かに零れている。……電話を切ると、俺はコートを掴んで部屋を飛び出した。優奈さんの家の扉を叩くと、彼女は涙の跡の残る顔で立っていた。"),
"d82": ("みんな、今日のお話はどうだった？　……ふふ、ありがとう。また来週、続きを読もうね。……あら悠太くん、来てくれてたの。手伝ってくれる？",
        "みんな、今日のお話はどうだった？　……ふふ、ありがとう。また来週、続きを読もうね。……あら悠太さん、来てくれてたの。手伝ってくれる？"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        needle = '"' + old + '"'
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, '"' + new + '"', 1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
