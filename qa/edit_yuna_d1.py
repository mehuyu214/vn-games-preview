"""W2 優奈 D1: 関係進展が一足飛びで、本作固有の葛藤が即日解消される。
レビュー D1「修理を手伝ったその日の夜に告白（d16）→そのまま初体験→
初夜のうちに妊娠の希望表明（d35x）まで進む。年上の司書と常連客という
立場の差、年齢差への優奈自身の不安（d14「年上の司書なんて、退屈じゃ
ない？」）は本作固有の良い火種だが、d16 の告白で即座に解消され、職場
での噂や周囲の目といった形で再燃することは一度もない」への対応。
着手前の再計測：d14 の不安提起に対し d16 は「退屈なんてとんでもない」
と即答するのみで、ためらい・迷い・価値観のすり合わせは 0 件。d16 の
告白の直前に、年齢差・立場の差と図書館での噂への迷いを入れる（桜 D1
の a21 と同型の text のみ 1 ノードの段取り追加）。d17「わたしでいいの？」
との接続も維持（彼女の不安への答えとして機能する）。
text のみ 1 ノード（他作品・構造は無変更）。全員成人・合意ありは維持。
"""
import io, sys

PATH = "data.js"

REPLACEMENTS = {
"d16": ("退屈なんてとんでもない。優奈さんの声も、仕草も、本を選ぶところも、全部好きです。――俺と、付き合ってください。",
        "……正直、迷わなかったわけじゃないんです。年上の司書さんと常連客で、歳も立場も違う。図書館で噂になったら、優奈さんに迷惑がかかるかもしれない。でも――退屈なんてとんでもない。優奈さんの声も、仕草も、本を選ぶところも、全部好きです。――俺と、付き合ってください。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        needle = '"' + old + '"'
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, '"' + new + '"', 1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
