"""W2 優奈 B4（残り）: 絵本シーンの二重提示の書き分け（優奈編）。
レビュー B4「絵本を取り出す描写は d108 と d220 が準一致（0.88）、開い
て読む描写は d145≈d223、物語の要約は d147≈d225 と、別場面同士で使い
回されており、d153 と d228、d157 と d235 は全文完全一致」への対応の
残り。

現状（実測）:
- d39／d217: 書庫の最奥の導入文が準一致（d217 は d39＋1文）。
- d145／d223: 「優奈さんは絵本をそっと開いた。ページをめくるたび、
  かすかな紙の匂いが立ちのぼる。」まで同一で、末尾（挿絵の描写）の
  み違う。
- d147／d225: 「優奈さんの声は、書庫の静寂にゆっくりと溶けていっ
  た。絵本の物語は、森の奥に住む小さな司書の」まで同一で、末尾のみ
  違う。
- d108／d220、d153／d228、d157／d235 は先行作業で書き分け済み。
- d221／d143／d186 の絵本の来歴（子供の頃に母が読んでくれた本）は
  整合済みで、C2 は実質解消。

改稿（text のみ 3 ノード、他作品・構造は無変更。初出側 d39／d145／
d147 を残し、後出側 d217／d223／d225 を書き換える）:
- d217: 導入を鍵のかかった貴重書棚の開扉に寄せる（d235 の「鍵のか
  かった貴重書棚を一度だけ振り返り」とも接続）。
- d223: 絵本を開く描写を、匂い・挿絵ではなく手垢とページの端の波打
  ちに寄せる（d222 の子供時代の読書→d224 の「本の中には、いつも
  誰かがいたの」へ接続）。
- d225: 読み聞かせの描写を、物語の要約ではなく声の低まりと指が挿絵
  をなぞる動きに寄せる（d226 の結末の台詞「物語は、誰かの心に住む
  の」へ接続）。
"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"d217": ("――書庫の最奥、普段は立ち入り禁止の貴重書棚。優奈さんは指で背表紙をなぞり、静かに微笑んだ。閉館後の図書館は、紙の匂いと静寂に満ちている。",
         "――書庫の最奥。鍵のかかった貴重書棚の前で、優奈さんは小さな鍵を取り出した。慣れた手つきで鍵を回すと、扉がかすかな音を立てて開いた。"),
"d223": ("優奈さんは絵本をそっと開いた。ページをめくるたび、かすかな紙の匂いが立ちのぼる。挿絵は手描きで、少しだけ色褪せている。",
         "優奈さんは絵本を膝の上に置き、ゆっくりと表紙を開いた。百年分の手垢が角を丸くし、ページの端は少しだけ波打っている。"),
"d225": ("優奈さんの声は、書庫の静寂にゆっくりと溶けていった。絵本の物語は、森の奥に住む小さな司書の、優しい日々の記録だった。",
         "読み進めるうちに、優奈さんの声は少しずつ低くなった。司書が動物たちに物語を届ける場面では、彼女の指が挿絵をそっとなぞる。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
