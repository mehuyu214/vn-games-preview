import io, sys

PATH = "data.js"

REPLACEMENTS = {
"e234": ("ねえ悠太。いつか、この庭園で、結婚式を挙げたいですわ。白いバラのアーチの下で。ねえ、いいかしら。",
        "ねえ悠太。……いつか、この庭園で、ずっとあなたと一緒にいられたら、素敵ですわね。白いバラのアーチの下で。ねえ、いいかしら。"),
"e235": ("もちろんです。……セレナ、約束ですよ。……白いバラのアーチの下で、必ず。",
        "もちろんです。……セレナ、俺も同じ気持ちです。……白いバラのアーチの下で、ずっと一緒にいましょう。"),
"e195": ("ねえ悠太、今日の午後は、麓の町へ買い物に行きましょう。……結婚式の準備の、第一歩として。",
        "ねえ悠太、今日の午後は、麓の町へ買い物に行きましょう。……バラ園の夢の、第一歩として。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
