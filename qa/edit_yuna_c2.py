"""W2 優奈 C2（残り）: 「百年ものの絵本」の来歴の再提示の解消（優奈編）。
レビュー C2「『百年ものの絵本』の来歴が4場面で食い違う」への対応の残り。

現状（実測・プレイ順は全4ルートで確認）:
- d221（pos 10）: 「わたし、子供の頃に読んだの。」――絵本の来歴の初出。
- d143（pos 31）: 「わたしが子供の頃、母に読んでもらった絵本なの。」――
  d221 と整合する母の読み聞かせの追加情報。残置。
- d107（pos 121）: 古本市の初版本で「貴重書棚にある、わたしの思い出の
  絵本と、同じ本なの」と別個体であることが明示済み。残置。
- d186（pos 104）: 「ねえ悠太さん、この絵本、知ってる？　……わたしが
  子供の頃、母が読んでくれたの。」――d221／d143 で既に確立した来歴を
  3度目に初出の体裁で言い直しており、d184「書庫に戻してちょうだい」
  の直後でもあるのに「この絵本、知ってる？」と問い直す。
- d187（pos 105）: 「いえ、初めて見ます。」――プレイ順では悠太は既に
  d217–d225（pos 6–11）と d142–d147（pos 30–33）でこの絵本を見て、
  読み聞かせまで受けており、事実と食い違う。

改稿（text のみ 2 ノード、他作品・構造は無変更）:
- d186: 来歴の再提示をやめ、書庫での読み聞かせ（d145–d147）の思い出
  として語り直す。「あのとき、母が読んでくれた声を、思い出したの」
  で d143 の母の声と接続し、d188「いつかね、この絵本を、わたしの
  子供にも読んであげたいの」へ自然につながる。
- d187: 「初めて見ます」をやめ、書庫で読んでもらった絵本だと覚えて
  いる応答に書き換え。末尾「優奈さんの大事な本だってことは、分かり
  ます。」は維持。
"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"d186": ("ねえ悠太さん、この絵本、知ってる？　……わたしが子供の頃、母が読んでくれたの。",
         "ねえ悠太さん、この絵本……書庫で読んであげたでしょう？　……あのとき、母が読んでくれた声を、思い出したの。"),
"d187": ("いえ、初めて見ます。……でも、優奈さんの大事な本だってことは、分かります。",
         "うん、覚えてます。……書庫で読んでくれた、あの絵本でしょう。……優奈さんの大事な本だってことは、分かります。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
