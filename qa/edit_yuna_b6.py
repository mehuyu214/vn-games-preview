"""W2 優奈 B6: 「翌朝」の二重演じの解消（優奈編）。
レビュー B6「初夜の後、d38x（夜が更けるまで）→d27（「おはよう、悠太さん」）
で朝を迎えた直後、d179 へ跳んで再び『――翌朝。……』が始まり、d180
『昨日の夜のこと、覚えてる？』と同じ朝・同じ感慨がもう一度提示される」
への対応。

実測（GOOD ルート、pos は 0 起点）:
- d61（pos 94）→ d38x（pos 95）: 「夜が更けるまで、二人は幾度も愛を
  囁き合った。翌朝、図書館のカウンターで交わす視線は、昨日までとは
  少しだけ違っていた。」――夜明けと翌朝のカウンターはここで既に語済み。
- d27（pos 96）: 「おはよう、悠太さん。……ふふ、これからは図書館でも
  家でも、わたしの特等席はあなたのそばね。」――同じ朝の中での挨拶。
  d27 は特等席の決め台詞の初出（B5 で d197 を書き分け済み）のため残置。
- d179（pos 97）: 「――朝の図書館。開館前のカウンターで、……」――
  3 度目の朝の提示。場面見出しで朝をもう一度開き直している。
- d180（pos 98）: 「昨日の夜のこと、覚えてる？　わたしは、もう一生
  忘れないわ。」――昨夜の感慨の 2 度目の提示（d38x／d27 で既出）。

改稿（text のみ 2 ノード、他作品・構造は無変更）:
- d179: 場面見出し「――朝の図書館。」を外し、同じ朝の続きとして
  「仕分けを続けていた」に。d27 の挨拶の直後、そのままカウンターでの
  作業風景へつながる。
- d180: 昨夜の問い直しをやめ、開館までの時間に仕分けの手伝いを頼む
  台詞に。d181「もちろんです。……優奈さん、朝から本の山ですね。
  手伝いますよ。」へ自然に接続し、d182 の同僚の指摘（今朝の雰囲気の
  違い）へも違和感なくつながる。初夜の感慨は d38x／d27 で既に十分。
"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"d179": ("――朝の図書館。開館前のカウンターで、優奈さんは本の仕分けをしていた。窓からの光が、彼女の横顔を優しく照らす。",
         "開館前のカウンターで、優奈さんは本の仕分けを続けていた。窓からの光が、彼女の横顔を優しく照らす。"),
"d180": ("ねえ悠太さん、昨日の夜のこと、覚えてる？　わたしは、もう一生忘れないわ。",
         "ねえ悠太さん、開館までまだ少し時間があるわ。……仕分け、手伝ってくれる？"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
