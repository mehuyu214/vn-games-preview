"""W2 桜 B4 賛辞の反復の残りの解消。
レビュー B4「さくらの写真への評『人を惹きつける力がある』が、悠太（a88）、
店主（a160）と別人物の口からほぼ同文で出るうえ、a163/a196/a236 でも
同趣旨が繰り返される」への対応。
着手前の再計測：a88 は「人を惹きつける力がある」の現行唯一の1件、
a160 は既に「人の心に残る写真になったよ」へ書き換え済み、
a163／a196／a236 は賛辞を含まない別場面に書き換え済み。
ただし a159 さくら「誰かの心に残る写真を撮りたくて」の直後で、
a160 店主が「人の心に残る写真になったよ」と同じ「心に残る」を
言い返しており、B4 の残留（隣接ノードでの賛辞の言い返し）が残る。
a160 を店主固有の声（5年間見守った大人。初めて現像した一枚を
今も取ってある）に書き換え、「心に残る」の反復を断つ。
残置：a88（現行唯一の「惹きつける」。a14「すごくいい」は a120 で
意図的に言及される自己言及のため残置。a171「伝わってくる」は
胎動の描写で別義）。
text のみ変更。ノードID・構造は不変。"""
import io, sys

PATH = "data.js"

REPLACEMENTS = {
"a160": ("店主は大きく頷き、さくらの頭をぽんと叩いた。「頑張りな。高校の頃、初めて自分で現像した桜の一枚から、ずっと見てきたけどな。あんたの写真は、人の心に残る写真になったよ」",
          "店主は大きく頷き、さくらの頭をぽんと叩いた。「頑張りな。高校の頃、初めて自分で現像した桜の一枚から、ずっと見てきたけどな。あんたの桜は今や、通りすがりの人の足を止める写真になったよ」"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        # text フィールドの引用符付き完全一致で置換（他ノードへの誤爆防止）
        needle = '"' + old + '"'
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, '"' + new + '"', 1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
