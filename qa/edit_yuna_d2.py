import io, sys

PATH = "data.js"

REPLACEMENTS = {
"d80": ("閉館後の図書室に、新しい物語のページが、静かにめくれていく。",
        "来月、図書室で小さな読み聞かせの会が開かれる。新しい物語のページが、静かにめくれていく。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        needle = old
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, new, 1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
