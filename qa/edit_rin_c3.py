import io, sys

PATH = "data.js"

REPLACEMENTS = {
"c41x": ("夜が明けるまで、二人は何度も愛を確かめ合った。翌日の学会発表で、凛はいつも以上に輝いていたという。\\n――俺だけが知る、あの夜の素顔を胸に秘めて。",
        "夜が明けるまで、二人は何度も愛を確かめ合った。\\n――俺だけが知る、あの夜の素顔を胸に秘めて。"),
"c200": ("――研究室の朝。二人の新しい日常が、静かに始まっていた。",
        "――学会の日。会場の最前列で、俺は凛さんの発表を見上げていた。緊張で震えていた声は、やがて芯のある響きに変わり、スライドの最後の一枚で、会場が大きな拍手に包まれた。凛さんは客席の俺を見つけ、ほっとしたように笑った。――打ち上げは帰り道の小さな店で。『美味しいコーヒー、奢るって言ったでしょ』と凛さんは笑い、乾杯のグラスを合わせた。『次は、温泉ね』"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        needle = '"' + old + '"'
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, '"' + new + '"', 1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
