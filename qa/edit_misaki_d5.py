"""W2 美咲 D5: 美咲の葛藤が置かれるたびに即解消され、人物が平たい
（OLを辞めた経緯 b82「合わなくて辞めて」は一言で終わり、夢への不安
b152「無謀だよね」も悠太の一言でその場で消え、二度と再燃しない。
22歳フリーターという立場の焦りや、妊娠と開店が重なる現実的な重圧は
作中に眠ったまま）。
再計測：「無謀」は b152 の1件のみで再燃なし。「焦り」「不安」「怖い」
は全編 0 件。「合わなくて辞めて」「フリーター」は b82 の1件のみ。
D1 は現行で解消済み（b186 は「あの朝、わたしの夢、笑わないで聞いて
くれたよね」と初披露ではなく回想の体裁。b150 も「休憩のときに話した
食堂のこと、覚えてる？」と既知前提）。D3 も現行 7 件で分散しており
集中なし（レビュー原文の23件から大幅減）。
b240（開店前夜。美咲の献立報告の締め）に、b82 の OL 辞職・22歳
フリーターと b152 の「無謀」を呼び戻す一節を追加し、妊娠と開店が
重なる重圧への怖さを本人の口から再燃させる。b241 の悠太の返答
（「美咲さんの朝ごはんなら、きっと大丈夫」「開店の朝、店の前で
待ってます」）はそのまま受けとして機能し、b242 の「早い鼓動」、
b243「記念にしよう？」へ自然に続く。葛藤は一言で消されず、夜の
営みへ持ち越される形になる。
text のみ変更。ノードID・構造は不変。全員成人・合意ありは維持。"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"b240": ("悠太くん、見て……明日の献立、やっと決まったの。……焼き魚は今朝の市場で選んだ鯖、卵焼きは甘めに、季節の小鉢は菜の花のおひたし。……ねえ、明日、ほんとに開店するんだね。",
        "悠太くん、見て……明日の献立、やっと決まったの。……焼き魚は今朝の市場で選んだ鯖、卵焼きは甘めに、季節の小鉢は菜の花のおひたし。……ねえ、明日、ほんとに開店するんだね。……OLを辞めた22歳のフリーターが、妊娠して、店まで開くなんて。……無謀だよね、やっぱり。……今さら、ちょっと怖くなっちゃった。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        needle = '"' + old + '"'
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, '"' + new + '"', 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
