"""W2 セレナ D1（関係進展の一足飛び）の解消。
再計測: e11 は「セレナ。俺も同じ気持ちです。身分なんて関係ない。俺はあなたが
好きだ。」で、e06 の選択肢文「身分が違います」が象徴する本作固有の火種
（身分差）を、告白のその場で一言で消している。e10「今夜は『先生』と呼ぶのを、
やめてもいいですか？」→ e11 → e12「嬉しい。わたしも、あなたを愛しています」
の流れは維持しつつ、e11 を「ためらい→それでも決意」の二段に書き換える。
雇われの家庭教師とヴェルディアの令嬢という身分の違いは言葉では消せない
と認めたうえで、気持ちまで消せるわけじゃないと告白する。e62 の「雇われていた
身から館の一員になる決断は、思ったより重かった」とも接続し、告白の重みが
後半の決断の重さに繋がる。e64 のプロポーズの「身分なんて関係ない」は、
重みを経たうえでの決意の言い直しとして残す。新たな未回収の糸は残さない。
全員成人・合意ありは維持。text のみ変更。ノードID・構造は不変。
"""
import io, sys

PATH = "data.js"

REPLACEMENTS = {
"e11": ("セレナ。俺も同じ気持ちです。身分なんて関係ない。俺はあなたが好きだ。",
        "セレナ。……正直、怖いよ。俺は雇われの家庭教師で、君はヴェルディアの令嬢だ。身分が違うのは、言葉じゃ消せない。……でも、だからって、君への気持ちまで消せるわけじゃない。俺も同じ気持ちです。俺はあなたが好きだ。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        needle = '"' + old + '"'
        n = src.count(needle)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(needle, '"' + new + '"', 1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
