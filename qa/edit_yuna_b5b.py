"""W2 優奈 B5（残り）: 百年ものの絵本を読む約束 d177／d215 の書き分け（優奈編）。
レビュー B5「百年ものの絵本を子に読む約束は d188／d229／d177／d215／
d253 と5回結ばれ、反復するほど1回ごとの重みが痩せていく」への対応の
残り。

現状（実測）:
- d188: 「そう。……いつかね、この絵本を、わたしの子供にも読んであげ
  たいの。……悠太さんと、一緒に。」――交際後の約束の初出。文言は
  別系統で残置。
- d229: 「ねえ、悠太さん。この絵本、いつか大勢の子供たちに読んであげ
  たいの。百年、眠っていた物語を、起こしてあげたいな。」――書き換え
  済み（大勢の子供たちへの読み聞かせ）。残置。
- d253: 「あぁ……温かい……ねえ悠太さん、栞が生まれたら、まず、この
  部屋で三人で眠るの。……それから、図書室にも連れて行ってあげたい
  な。」――書き換え済み。残置。
- d177: 「あぁ……温かい……ねえ悠太さん、この子が生まれたら、百年も
  のの絵本を読んであげるの。……わたしと、あなたと、この子で。」――
  R18場面での約束の初出として残置。
- d215: 「あぁ……温かい……ねえ悠太さん、栞が生まれたら、百年ものの
  絵本を読んであげるの。……わたしと、あなたと、栞で。」――d177 と
  「この子」→「栞」の1語違いのみの準一致。命名の夜（d209–d216）の
  ブロックで、d216 の「名前の本」と接続する。

改稿（text のみ 1 ノード、他作品・構造は無変更）:
- d215: 命名の夜のモチーフ（名前の本）に寄せ、「栞が生まれたら、こ
  の絵本を、栞の名前の本と並べて読んであげるの。……百年、眠ってい
  た物語が、栞の物語になるのよ。」に書き換え。d177 の単純な約束と
  は別の言い回しになり、d216 の名前の本とも接続する。
"""
import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"d215": ("あぁ……温かい……ねえ悠太さん、栞が生まれたら、百年ものの絵本を読んであげるの。……わたしと、あなたと、栞で。",
         "あぁ……温かい……ねえ悠太さん、栞が生まれたら、この絵本を、栞の名前の本と並べて読んであげるの。……百年、眠っていた物語が、栞の物語になるのよ。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
