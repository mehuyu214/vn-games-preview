import io, os, sys

PATH = "data.js"

REPLACEMENTS = {
"b143": ("――連絡先を交換し終えた頃、夜勤は明け方を迎えていた。窓の外では、雨上がりの朝日が静かに街を染め始めている。",
        "――数日後の夜勤明け。窓の外では、雨上がりの朝日が静かに街を染め始めている。"),
"b05": ("窓の外は本格的な雨。閉店作業を終える頃には、傘があってもずぶ濡れになるような土砂降りだった。",
        "窓の外は本格的な雨。夜が更ける頃には、傘があってもずぶ濡れになるような土砂降りだった。"),
}

def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()
    for nid, (old, new) in REPLACEMENTS.items():
        n = src.count(old)
        if n != 1:
            print(f"FAIL {nid}: count={n}")
            sys.exit(1)
        src = src.replace(old, new, 1)
    # 一時ファイルへ書き出して検証してから置き換える（直接 open("w") は
    # 書き込み失敗時に元ファイルを 0 バイト化するため使わない）。
    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8") as f:
        f.write(src)
        f.flush()
        os.fsync(f.fileno())
    if os.path.getsize(tmp) != len(src.encode("utf-8")):
        print("FAIL: tmp size mismatch")
        sys.exit(1)
    os.replace(tmp, PATH)
    print(f"OK: {len(REPLACEMENTS)} nodes rewritten")

if __name__ == "__main__":
    main()
